"""Economic calendar ingestion and news blackout window processor.

Reads calendar CSV exports generated by MQL5 ExportCalendar script,
normalizes timestamps to UTC, and extracts high-impact macroeconomic events
(e.g., Non-Farm Payrolls, CPI, FOMC, Fed Interest Rate Decisions).
"""

from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional
import pandas as pd
from python_brain.logger import app_logger


HIGH_IMPACT_KEYWORDS = [
    "NON-FARM",
    "NFP",
    "CONSUMER PRICE INDEX",
    "CPI",
    "FOMC",
    "FEDERAL FUNDS RATE",
    "INTEREST RATE",
    "GDP",
    "UNEMPLOYMENT RATE",
    "RETAIL SALES",
    "PMI",
]


class CalendarLoader:
    """Loads and standardizes economic calendar events for news filtering."""

    def __init__(self, broker_utc_offset_hours: float = 0.0):
        self.broker_utc_offset_hours = broker_utc_offset_hours

    def load_from_csv(self, csv_path: str) -> pd.DataFrame:
        """Load exported CSV file and convert to clean UTC DataFrame."""
        path = Path(csv_path)
        if not path.exists():
            raise FileNotFoundError(f"Calendar file not found at: {csv_path}")

        df = pd.read_csv(path)
        if df.empty:
            return df

        # Parse broker timestamps
        df["time_broker"] = pd.to_datetime(df["time_broker"])
        df["time_utc"] = df["time_broker"] - pd.to_timedelta(
            self.broker_utc_offset_hours, unit="h"
        )

        # Flag high-impact events
        is_high_importance = df["importance"].astype(str).str.upper() == "HIGH"
        name_upper = df["event_name"].astype(str).str.upper()
        matches_keyword = name_upper.apply(
            lambda name: any(kw in name for kw in HIGH_IMPACT_KEYWORDS)
        )

        df["is_high_impact"] = is_high_importance | matches_keyword

        # Clean numerical fields
        for col in ["actual_value", "forecast_value", "previous_value"]:
            if col in df.columns:
                df[col] = pd.to_numeric(df[col], errors="coerce")

        df = df.sort_values("time_utc").reset_index(drop=True)
        app_logger.info(
            f"Loaded {len(df)} calendar events ({df['is_high_impact'].sum()} high impact) from {csv_path}"
        )
        return df

    def get_blackout_windows(
        self,
        df: pd.DataFrame,
        before_minutes: int = 30,
        after_minutes: int = 30,
    ) -> List[tuple]:
        """Compute (start_utc, end_utc) blackout windows around high impact events."""
        if df.empty:
            return []

        high_impact = df[df["is_high_impact"] == True]
        windows = []

        for _, row in high_impact.iterrows():
            event_time = row["time_utc"]
            window_start = event_time - pd.Timedelta(minutes=before_minutes)
            window_end = event_time + pd.Timedelta(minutes=after_minutes)
            windows.append((window_start, window_end, row["event_name"]))

        return windows

